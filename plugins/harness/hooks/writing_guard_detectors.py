def analyze(src, mono_title=False, is_html=False):
    """Every signal for one text, split into the tier that may block and the
    tier that may not."""
    text = Text(src, mono_title=mono_title, is_html=is_html)
    raw = raw_signals(text)
    fired = sorted(name for name, hits in raw.items() if hits)
    return {
        'blocking': [n for n in fired if n in BLOCKING_SIGNALS],
        'advisory': [n for n in fired if n not in BLOCKING_SIGNALS],
        'counts': {name: len(hits) for name, hits in raw.items()},
        'title_present': text.title is not None,
        'sentences_read': len(text.sentences),
    }


def deny_message(blocking):
    """What a denied writer is told: the principle, the target, the skill.

    Never the span, never its position, never the count of them. A writer
    handed the failing words edits those words and ships the same text; a
    writer handed the principle has to read their own opening again.
    """
    principles, targets = [], []
    for name in blocking:
        principle, target = PRINCIPLES[name]
        if principle not in principles:
            principles.append(principle)
            targets.append(target)
    if not principles:
        return ''
    return ('Blocked by the writing guard.\n'
            'What a reader meeting this cold runs into: %s.\n'
            'Write the passage again so that %s.\n'
            'The rules, and the one register that has passed a reader, are in '
            '%s. Work from them and write it fresh rather than editing out '
            'whatever you think this gate objected to - it names no phrase on '
            'purpose, because swapping those words is not the same as writing '
            'something a reader can follow.'
            % ('; '.join(principles), '; '.join(targets), SKILL_PATH))


