# ============================================================ prose extraction
# Verbatim from the 2026-08-15 tool's proto/extract_prose.py, by way of the
# frozen sweep/reference-impl/_shared.py. Every mechanism reads the same
# segmentation, so "the first sentence" means one thing across the file.
BLOCK_TAGS = ['p', 'li', 'td', 'th', 'h1', 'h2', 'h3', 'summary', 'title',
              'br', 'tr', 'div', 'section', 'details', 'ol', 'ul', 'table',
              'thead', 'tbody', 'header', 'main']
SENT_SPLIT = re.compile(r'(?<=[.!?])\s+(?=[A-Z0-9“(])')
WORD_RE = re.compile(r'[A-Za-z0-9]')


def _mask_quotes(text):
    """Curly-quoted passages are someone else's words; mask them out."""
    quotes = re.findall(r'“(.*?)”', text, flags=re.S)
    masked = re.sub(r'“.*?”', ' “QUOTE” ', text, flags=re.S)
    return masked, quotes


def blocks_from_html(src):
    src = re.sub(r'<!--.*?-->', ' ', src, flags=re.S)
    src = re.sub(r'<style>.*?</style>', ' ', src, flags=re.S)
    src = re.sub(r'<script.*?</script>', ' ', src, flags=re.S)
    src = re.sub(r'<svg.*?</svg>', ' ', src, flags=re.S)
    src = re.sub(r'<span class="path">.*?</span>', ' «PATH» ', src, flags=re.S)
    src = re.sub(r'<span class="numname">.*?</span>', ' «ID» ', src, flags=re.S)
    src = re.sub(r'<(?:pre|code|blockquote)[^>]*>.*?</(?:pre|code|blockquote)>',
                 ' ', src, flags=re.S)
    for tag in BLOCK_TAGS:
        src = re.sub(r'</?%s[^>]*>' % tag, '\n@@B@@\n', src)
    src = re.sub(r'<[^>]+>', ' ', src)
    src = html_mod.unescape(src)
    out = []
    for b in src.split('@@B@@'):
        b = re.sub(r'\s+', ' ', b).strip()
        if re.search(r'[A-Za-z]', b):
            out.append(b)
    return out


def blocks_from_markdown(src):
    src = re.sub(r'^```.*?^```', ' ', src, flags=re.S | re.M)   # fenced code
    src = re.sub(r'^(?: {4}|\t).*$', ' ', src, flags=re.M)      # indented code
    src = re.sub(r'`[^`]+`', ' «CODE» ', src)                   # inline code
    src = re.sub(r'https?://\S+', ' «URL» ', src)
    src = re.sub(r'(?<![\w])(~?/[\w.\-/]+/[\w.\-/]+)', ' «PATH» ', src)
    src = re.sub(r'^#+\s*', '', src, flags=re.M)
    src = re.sub(r'^[=\-]{3,}\s*$', '\n\n', src, flags=re.M)
    src = re.sub(r'\*\*([^*]+)\*\*', r'\1', src)
    src = re.sub(r'(?<!\w)\*([^*\n]+)\*(?!\w)', r'\1', src)
    out = []
    for para in re.split(r'\n\s*\n', src):
        for piece in re.split(r'\n(?=\s*(?:[-*+]|\d+\.)\s)', para):
            piece = re.sub(r'^\s*(?:[-*+]|\d+\.)\s+', '', piece.strip())
            piece = re.sub(r'\s+', ' ', piece).strip()
            if re.search(r'[A-Za-z]', piece):
                out.append(piece)
    return out


def extract_text(src, is_html=False):
    """The document as prose: blocks, then sentences, quotes masked.

    The prototypes read a path. A hook also reads commit messages, which were
    never files, so the source string is the parameter here. Nothing else about
    the extraction changed.
    """
    raw_blocks = blocks_from_html(src) if is_html else blocks_from_markdown(src)
    blocks, all_quotes = [], []
    for b in raw_blocks:
        masked, quotes = _mask_quotes(b)
        all_quotes.extend(quotes)
        blocks.append(masked)
    sentences = []
    for i, b in enumerate(blocks):
        for s in SENT_SPLIT.split(b):
            s = s.strip()
            if re.search(r'[A-Za-z]', s):
                sentences.append((i, s))

    def wc(t):
        return len([w for w in re.split(r'\s+', t)
                    if WORD_RE.search(w) and not w.startswith('«')])
    return {'blocks': blocks, 'sentences': sentences,
            'words': sum(wc(b) for b in blocks), 'quotes': all_quotes,
            'raw': src}


