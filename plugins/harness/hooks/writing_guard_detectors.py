def strip_section_label(sentence):
    return SECTION_LABEL.sub('', sentence)


def words(text):
    return [w for w in text.split()
            if WORD_RE.search(w) and not w.startswith('«')]


def tok(word):
    return word.strip('.,;:!?()[]{}"\'—“”‘’`').lower()


def first_finite_verb(tokens):
    for n, w in enumerate(tokens):
        if tok(w) in VERB_FORMS:
            return n
    return None


def is_abstract(word):
    t = tok(word)
    if t in ABSTRACT_HEADS:
        return True
    return len(t) > 5 and t.endswith(NOMINAL_SUFFIX)


def names_an_actor(text):
    """Does this span name anybody the reader can picture?"""
    toks = []
    for w in text.split():
        t = tok(w)
        toks.append(t)
        if "'" in t or '’' in t:
            toks.append(re.split(r"['’]", t)[0])
    if any(t in FIRST_SECOND for t in toks):
        return True
    if any(t in ROLE_NOUNS for t in toks):
        return True
    return bool(PROPER_NAME.search(text))


# ======================================================== definite opacity
# Verbatim from the frozen sweep/reference-impl/_shared.py (itself a parity-
# tested copy of the sweep's detector), with one parameter added:
# `suspend_e3_in` names the sentence indices where the postnominal exemption
# does not apply. See fix 1 in the module docstring.
DEF_DET = r'(?:the|its|their|his|her|our|this|that|these|those)'
_BOUND_WORDS = sorted(VERB_FORMS | STOPWORDS | AUX_VERBS,
                      key=lambda w: (-len(w), w))
HEAD_AFTER_WIDE = (
    r"(?=\s*(?:[.,;:!?)»\"'’”—]|$)"
    r"|\s*(?:'s|’s)\b"
    r"|\s+(?:" + '|'.join(re.escape(w) for w in _BOUND_WORDS) + r")\b"
    r"|\s+[a-z][a-z'-]*(?:ed|ing|es|s)\b)")
NP_RE = re.compile(
    r'\b(' + DEF_DET + r')\s+((?:[a-z][a-z-]{2,}\s+){0,2}?)([a-z][a-z-]{2,})\b'
    + HEAD_AFTER_WIDE)
THAT_AFTER_NOUN = re.compile(r"([a-z][a-z'-]*)\s+$")

E1_WORDS = set('first last best worst next previous only same entire whole '
               'main final initial'.split())
E2_HEADS = set('fact result reason idea conclusion point question problem way '
               'case thing kind sort number amount rest end beginning'.split())
E2_NEXT = set('that of why how which to'.split())
E7_HEADS = set('year month day week time morning evening date moment period '
               'afternoon night hour minute'.split())
E8_HEADS = set('reader user system file repo code team world sun government '
               'internet shell terminal screen page document text draft '
               'author writer language english web browser network disk '
               'machine computer keyboard'.split())
PREPOSITIONS = set('of in on at to from by with for about into through during '
                   'before after above below between under over against '
                   'within without across'.split())
RELATIVES = set('that which who whom whose where when'.split())


def _stem(w):
    for suf in ('ing', 'es', 'ed', 's'):
        if w.endswith(suf) and len(w) > len(suf) + 2:
            return w[:-len(suf)]
    return w


def _words_lower(s):
    return [w.strip('.,;:!?()[]"\'—“”').lower()
            for w in s.split() if re.search(r'[A-Za-z0-9]', w)
            and not w.startswith('«')]


def definite_opacity(sentences, k_window=4, suspend_e3_in=()):
    """Definite noun phrases whose referent the text never introduced.

    Returns one finding per definite phrase: UNRESOLVED, resolved, or exempt
    with the exemption's code. `suspend_e3_in` is the set of sentence indices
    where E3 (a preposition or relative follows the noun) does not exempt.
    """
    suspend = set(suspend_e3_in)
    stems_by_sentence = [{_stem(w) for w in _words_lower(s)} for s in sentences]
    findings = []

    for i, s in enumerate(sentences):
        low = s.lower()
        aligned = len(low) == len(s)
        for m in NP_RE.finditer(low):
            det = m.group(1)
            mods = m.group(2).split()
            head = m.group(3)
            if head in STOPWORDS or head in VERB_FORMS or head.endswith('ly'):
                continue
            if det == 'that':
                before = THAT_AFTER_NOUN.search(low[:m.start()])
                if before and before.group(1) not in STOPWORDS \
                        and before.group(1) not in VERB_FORMS \
                        and not before.group(1).endswith(('ed', 'ing')):
                    continue    # relative pronoun, not a determiner
            phrase = s[m.start():m.end()] if aligned else m.group(0)
            rest = low[m.end():].lstrip()
            next_tok = re.match(r"[a-z][a-z'-]*", rest)
            next_tok = next_tok.group(0) if next_tok else ''

            ex = None
            if any(w.endswith('est') or w in E1_WORDS for w in mods):
                ex = 'E1'
            elif head in E2_HEADS and next_tok in E2_NEXT:
                ex = 'E2'
            elif (next_tok in PREPOSITIONS or next_tok in RELATIVES) \
                    and i not in suspend:
                ex = 'E3'
            elif re.match(r',\s+[A-Z]', s[m.end():] if aligned else ''):
                ex = 'E4'
            elif re.search(r'\b(?:is|are|was|were|be|been|being)\s*$',
                           low[:m.start()]):
                ex = 'E5'
            elif aligned and any(c.isupper() for c in s[m.start(2):m.end(3)]):
                ex = 'E6'
            elif head in E7_HEADS:
                ex = 'E7'
            elif head in E8_HEADS or ' '.join(mods + [head]) in E8_HEADS:
                ex = 'E8'
            if ex:
                findings.append({'s': i, 'verdict': 'exempt', 'code': ex,
                                 'phrase': phrase})
                continue

            st = _stem(head)
            resolved = False
            for j in range(max(0, i - k_window), i):
                if st in stems_by_sentence[j]:
                    resolved = True
                    break
                pj = sentences[j].lower()
                if re.search(r'\b(?:a|an|one|some|each|every|another|new)\s+'
                             r'(?:[a-z-]+\s+){0,2}' + re.escape(st), pj):
                    resolved = True
                    break
                if re.search(re.escape(st) + r'[a-z]*\b\s*(?:is|are|means|:|—)',
                             pj):
                    resolved = True
                    break
            if not resolved and re.search(
                    re.escape(head) + r'\s*\([^)]{4,60}\)', low):
                resolved = True
            findings.append({'s': i, 'phrase': phrase,
                             'verdict': 'resolved' if resolved else 'UNRESOLVED'})
    return findings


# ==================================================================== the text
PREFIX_SENTENCES = 3     # the opening window: what the user read before stopping
MAX_SENTENCES = 200      # advisory shapes stop here; a hook has a timeout


class Text(object):
    """One text, read once, with the positions every mechanism shares.

    `title` is a commit's subject line (mono_title), a markdown document's top
    heading, or an HTML page's <title>/<h1>. It is None when the text has none,
    and a title-scoped mechanism then reports nothing rather than guessing.
    """

    def __init__(self, src, mono_title=False, is_html=False):
        self.doc = extract_text(src, is_html=is_html)
        self.raw = self.doc['raw']
        self.is_html = is_html
        self.mono_title = mono_title
        self.sentences = [s for _, s in self.doc['sentences']][:MAX_SENTENCES]

        lines = [l.rstrip() for l in self.raw.splitlines()]
        nonblank = [l.strip() for l in lines if l.strip()]
        self.first_line = nonblank[0] if nonblank else ''

        if is_html:
            self.title = self._html_title()
            self.headings = [self._strip_tags(m.group(2))
                             for m in HTML_HEADING.finditer(self.raw)][:100]
        else:
            heading = ATX_HEADING.match(self.first_line)
            if mono_title:
                self.title = self.first_line
            elif heading:
                self.title = heading.group(2)
            else:
                self.title = None
            self.headings = [ATX_HEADING.match(l).group(2) for l in lines
                             if ATX_HEADING.match(l)][:100]

        # Which extracted sentence IS the title, so the first BODY sentence can
        # be told apart from it.
        self.title_sentence = None
        if self.title is not None and self.sentences:
            head = re.sub(r'\s+', ' ', self.title).strip()
            if re.sub(r'\s+', ' ', self.sentences[0]).strip() == head:
                self.title_sentence = 0
        self.first_body_index = 1 if self.title_sentence == 0 else 0

    def _strip_tags(self, s):
        return re.sub(r'\s+', ' ', html_mod.unescape(
            re.sub(r'<[^>]+>', ' ', s))).strip()

    def _html_title(self):
        m = HTML_TITLE.search(self.raw)
        if m and self._strip_tags(m.group(1)):
            return self._strip_tags(m.group(1))
        for h in HTML_HEADING.finditer(self.raw):
            if h.group(1) == '1' and self._strip_tags(h.group(2)):
                return self._strip_tags(h.group(2))
        return None

    def window(self):
        """The opening: the first PREFIX_SENTENCES sentences, with indices.

        For a commit message the subject line is sentence 0, so the window is
        the subject plus the first two body sentences - what the user described
        reading before they stopped.
        """
        return list(enumerate(self.sentences))[:PREFIX_SENTENCES]

    def positions(self):
        """Every prominent position, in reading order: (kind, text)."""
        out = []
        if self.title is not None:
            out.append(('title', self.title))
        idx = self.first_body_index
        if idx < len(self.sentences):
            out.append(('first_sentence', self.sentences[idx]))
        for h in self.headings:
            if self.title is not None and h.strip() == self.title.strip():
                continue
            out.append(('heading', h))
        return out


# ================================================== mechanism 1: opening referent
def _unbound_pronouns(window):
    """Pronouns in the opening with nothing before them to point at.

    Deliberately generous: it reports a pronoun only when the window offers
    NOTHING it could refer to, which is the case the user described
    ("'returning' to what?" with nothing yet named).
    """
    hits = []
    seen_before = ''
    for idx, sentence in window:
        body = strip_section_label(sentence)
        toks = body.split()
        for i, w in enumerate(toks):
            t = tok(w)
            bare_demo = (i == 0 and BARE_DEMONSTRATIVE.match(body)
                         and t in DEMONSTRATIVES | {'it'})
            if t not in PRONOUN_LEG and not bare_demo:
                continue
            if t == 'it':
                tail = [tok(x) for x in toks[i + 1:i + 8]]
                if tail and tail[0] in ('is', 'was', 'are', 'were'):
                    rest = tail[1:]
                    if 'that' in rest or (rest and (
                            rest[0] in DUMMY_IT_ADJ
                            or rest[0].endswith(DUMMY_IT_ADJ_SUFFIX))):
                        continue          # "it is clear that ..." names nobody
            before = seen_before + ' ' + ' '.join(toks[:i])
            if ANTECEDENT_NP.search(before) or PROPER_NAME.search(before) \
                    or any(tok(x) in FIRST_SECOND for x in before.split()):
                continue
            hits.append(w.strip('.,;:!?'))
        seen_before += ' ' + body
    return hits


def opening_referent(text):
    """Unintroduced definite phrases in the title and in the opening window."""
    window = text.window()
    indices = [i for i, _ in window]
    sentences = [s for _, s in window]
    ti = text.title_sentence

    frozen = definite_opacity(sentences)
    fixed = definite_opacity(sentences, suspend_e3_in=indices)

    def unresolved(findings, only=None):
        return [f['phrase'] for f in findings if f['verdict'] == 'UNRESOLVED'
                and (only is None or f['s'] == only)]

    title_applicable = text.title is not None and ti is not None
    return {
        'title_present': text.title is not None,
        'title_read_as_sentence': title_applicable,
        'title_frozen': unresolved(frozen, ti) if title_applicable else [],
        'title_e3_suspended': unresolved(fixed, ti) if title_applicable else [],
        'window_frozen': unresolved(frozen),
        'window_e3_suspended': unresolved(fixed),
        'window_e3_exempt': [f['phrase'] for f in frozen
                             if f['verdict'] == 'exempt' and f['code'] == 'E3'],
        'unbound_pronouns': _unbound_pronouns(window),
        'window_sentence_count': len(sentences),
    }


# ================================================ mechanism 2: front-loaded framing
N_WORDS_BEFORE_POINT = 6      # the user's own count, round-1 item r1-52
PHRASE_WORD_CAP = 12          # a generosity bound on "phrase, not clause"
COLON_OPENER = re.compile(r'^([^:]{2,200}):\s')
PARENTHETICAL = re.compile(r'\([^)]*\)')
FRONT_CLOSER = re.compile(r'[,:;—]|--')
INDEFINITE_PRONOUNS = set("""nothing something anything everything nobody
somebody anybody everybody none""".split())
DEFINITE_OPENER = re.compile(r'^(?:the|this|that|these|those|its|their)\b', re.I)


def _colon_span(body):
    """The phrase a sentence puts in front of its colon, if it is a phrase."""
    m = COLON_OPENER.match(body)
    if not m:
        return None
    span = m.group(1)
    n = len(words(span))
    if n < 2 or n > PHRASE_WORD_CAP:
        return None
    probe = PARENTHETICAL.sub(' ', span)      # a gloss inside an NP is still NP
    if first_finite_verb(probe.split()) is not None:
        return None
    if names_an_actor(probe):
        return None
    return span.strip(), probe


def _shape_a(body):
    """Nominal framing phrase, then a colon, then the point."""
    got = _colon_span(body)
    if not got:
        return None
    span, probe = got
    heads = [tok(w) for w in probe.split() if is_abstract(w)]
    if not heads:
        return None
    return {'shape': 'nominal_framing_colon', 'span': span,
            'words_before_point': len(words(span))}


def _shape_d(body):
    """A definite phrase used as a frame: "The result: ...".

    The advisory-only fix from ROUND2-ANALYSIS.md F.4. Shape A misses it
    because "result" is not an abstract head, and deciding that it is one while
    reading the accepted texts would be fitting; this reports the definite
    determiner instead, which is the user's own rule (define it or name it in
    full) applied to a framing phrase.
    """
    got = _colon_span(body)
    if not got:
        return None
    span, probe = got
    if not DEFINITE_OPENER.match(probe.strip()):
        return None
    if _shape_a(body):
        return None                    # already reported as the abstract shape
    return {'shape': 'definite_framing_colon', 'span': span,
            'words_before_point': len(words(span))}


def _fronting_marker(first_word):
    t = tok(first_word)
    if t in INDEFINITE_PRONOUNS:
        return None                    # a subject, not fronted material
    if t in SUBORDINATORS or t in FRONTING_PREPOSITIONS:
        return 'subordinator or preposition'
    if len(t) > 4 and t.endswith(('ing', 'ed')):
        return 'participle'
    return None


def _shape_b(body):
    """Fronted material that takes six or more words to reach the point."""
    toks = body.split()
    if not toks or not _fronting_marker(toks[0]):
        return None
    n = 0
    for i, w in enumerate(toks):
        if i and tok(w) in VERB_FORMS:
            break                              # the point: a finite verb
        n += 1
        if FRONT_CLOSER.search(w):
            break                              # the point: the fronting comma
    span = ' '.join(toks[:n])
    if len(words(span)) < N_WORDS_BEFORE_POINT:
        return None
    return {'shape': 'fronted_clause', 'span': span.strip(),
            'words_before_point': len(words(span))}


def _shape_c(body):
    """Abstract heads stacked in front of the first finite verb."""
    toks = body.split()
    v = first_finite_verb(toks)
    span_toks = (toks[:v] if v is not None else toks)[:PHRASE_WORD_CAP]
    if len(span_toks) < 2:
        return None
    span = ' '.join(span_toks)
    if names_an_actor(span):
        return None
    if len([tok(w) for w in span_toks if is_abstract(w)]) < 2:
        return None
    return {'shape': 'abstract_np_chain', 'span': span.strip(),
            'words_before_point': len(words(span))}


SHAPES = (_shape_a, _shape_b, _shape_c, _shape_d)


def front_loaded_framing(text):
    """Framing phrases, split by shape and by position."""
    opener_indices = {i for i in (text.title_sentence, text.first_body_index)
                      if i is not None}
    matches = []
    for i, sentence in enumerate(text.sentences):
        body = strip_section_label(sentence)
        for shape in SHAPES:
            hit = shape(body)
            if hit:
                hit['position'] = ('opener' if i in opener_indices else 'body')
                matches.append(hit)
    return {
        'colon_opener': [m for m in matches
                         if m['position'] == 'opener'
                         and m['shape'] == 'nominal_framing_colon'],
        'fronted_opener': [m for m in matches
                           if m['position'] == 'opener'
                           and m['shape'] in ('fronted_clause',
                                              'abstract_np_chain')],
        'definite_colon': [m for m in matches
                           if m['shape'] == 'definite_framing_colon'],
        'body': [m for m in matches if m['position'] == 'body'
                 and m['shape'] != 'definite_framing_colon'],
    }


# ================================================ mechanism 3: positional aphorism
# Eight patterns copied verbatim from the 2026-08-15 proto/linter.py
# APHORISM_PATTERNS (the set config-freeze.json demoted); the ninth was added
# 2026-08-21 from the user's own wording, because the frozen is-X-not-Y needs a
# copula and the shape they quoted is the bare contrast.
APHORISM_PATTERNS = {
    'is-X-not-Y':   re.compile(r'\b(?:is|are|was|were)\s+[^.,;]{3,40},\s*not\s+'),
    'not-because':  re.compile(r'\bnot because\b', re.I),
    'the-very':     re.compile(r'\bthe very\s+\w+', re.I),
    'exactly-when': re.compile(r'\bexactly\s+(?:when|where|what|how)\b', re.I),
    'turns-into':   re.compile(r'\bturns?\s+\w[\w\s-]{0,35}\binto\b'),
    'never-always': re.compile(r'^(?:Never|Always)\b'),
    'that-is-the':  re.compile(r'\bThat is (?:not )?(?:the|what|why|how)\b'),
    'em-dash-flip': re.compile(r'—\s*(?:it|that|this)\s+(?:is|was)\b'),
    'x-not-y-contrast': re.compile(
        r',\s*not\s+(?:just|only|merely|simply|the)?\s*\S'),
}


def _aphorism_matches(line):
    return [name for name, pat in sorted(APHORISM_PATTERNS.items())
            if pat.search(line)]


def positional_aphorism(text):
    """The quotable contrast, counted apart by position.

    The title is reported alone because that is the only position round 2
    supports: an accepted round-1 commit carries the same construction in body
    text, doing clarifying work.
    """
    out = {'title': [], 'prominent_other': [], 'body': []}
    prominent_lines = set()
    for kind, line in text.positions():
        prominent_lines.add(re.sub(r'\s+', ' ', line).strip())
        key = 'title' if kind == 'title' else 'prominent_other'
        out[key].extend(_aphorism_matches(line))
    for sentence in text.sentences:
        if re.sub(r'\s+', ' ', sentence).strip() in prominent_lines:
            continue
        out['body'].extend(_aphorism_matches(strip_section_label(sentence)))
    return out


