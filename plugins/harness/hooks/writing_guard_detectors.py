"""The writing guard's detectors: three mechanisms the user named, one file.

    python3 writing_guard_detectors.py <file> [--mono-title]

WHERE THESE MECHANISMS COME FROM
--------------------------------
Two pre-registered labeling rounds (51 answered items, 2026-08-21) produced
three mechanisms in the user's own words, recorded in the initiative's
`sweep/ROUND1-READOUT.md` and validated at n=1 in `sweep/ROUND2-ANALYSIS.md`:

  opening_referent      first lines that do not establish who, what or where
                        ("what instance? what 'still'? 'returning' to what?")
  front_loaded_framing   an abstract framing phrase ahead of the point
                        ("I've read 6 words, yet I have no idea what the
                        sentence is about ... I hate this recursive sentence
                        structure")
  positional_aphorism   the "[X], not [Y]" shape in a title
                        ("completely unaccaptable stuff")

The code is vendored from that initiative's round-2 prototypes
(`sweep/round2-prototypes/{opening_referent,front_loaded_framing,
positional_aphorism,_proto_shared}.py`), which in turn copied their prose
segmentation from the 2026-08-15 linter's `proto/extract_prose.py` and their
definite-opacity detector from the frozen `sweep/reference-impl/_shared.py`.
Vendored rather than imported: a hook runs on a user's machine with nothing but
python3, and it must keep producing the same verdicts when the research tree
moves. Standard library only, for the same reason.

TWO FIXES THE ROUND-2 LABELS FORCED, AND ONE THEY DID NOT
---------------------------------------------------------
1. The E3 postnominal exemption is suspended inside the opening window. The
   frozen detector exempts a definite phrase when a preposition follows its
   noun, which is why "The instance still froze on returning..." - the phrase
   the user quoted twice as their reason for rejecting a text - was invisible
   to it. ROUND2-ANALYSIS.md F.2. Both readings are computed, because which one
   may block is decided by false-positive validation, not by this file.
2. A definite phrase closed by a colon is reported, so that "The result: ..."
   is not scored zero. The user flagged that span; the frozen shape test missed
   it because "result" is not an abstract head. ROUND2-ANALYSIS.md F.4. It is
   advisory-only: the fix was never pre-registered, so it has no standing to
   block anything.
3. NOT fixed: the two head-boundary parser defects named in ROUND2-ANALYSIS.md
   F.4 ("the 202 user turns that followed them" read as "that followed").
   Repairing a parser while looking at the three texts it must stay quiet on is
   how a detector gets fitted to three labels. The defect instead does what it
   should: it makes the whole-window count fire on accepted writing, and the
   validation harness disqualifies that count from blocking.

TIERS
-----
Only signals listed in BLOCKING_SIGNALS below may deny a tool call, and that
tuple is generated by `tests/writing-guard-fp-validation.py` from the texts the
user accepted - never computed here at run time. Every other signal is
advisory: recorded in a bypass entry, reported by the harness, never a block.
"""
